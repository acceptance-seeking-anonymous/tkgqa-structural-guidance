#!/usr/bin/env python3
"""rob_generate_r1.py -- R1 perturbed set: qtype-stratified 2,000-question test sample, deterministic P1 / P2 variants,
and P3 rewrites of the 600-question pool generated by an API LLM (names and times protected by the prompt), filtered by
the gold-free mechanical checks and the LLM judge, with at most two attempts per question (rob_common.py: prompts,
checks, sampling). Never reads answers. Output: multitq_robustness_perturbed_set.json.

  python rob_generate_r1.py --test-json $DATA_DIR/questions/test.json [--rule protocol/multitq_robustness_rule.json] \
         [--out multitq_robustness_perturbed_set.json]
Generator / judge endpoint and model IDs: robustness/llm_client.py (GEN_MODEL_ID, JUDGE_MODEL_ID).
"""
import argparse, collections, datetime, hashlib, json, os, sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(REPO, 'src', 'struct'))
sys.path.insert(0, os.path.join(REPO, 'robustness'))
import rob_common as RC          # noqa: E402
import mtq_lib as L              # noqa: E402
import llm_client                # noqa: E402

CHUNK = 300


def fsha(p):
    return hashlib.sha256(open(p, 'rb').read()).hexdigest()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--test-json', required=True)
    ap.add_argument('--rule', default=None, help='registered rule JSON (its sha256 field is recorded)')
    ap.add_argument('--out', default='multitq_robustness_perturbed_set.json')
    ap.add_argument('--max-concurrency', type=int, default=16)
    a = ap.parse_args()

    test = json.load(open(a.test_json))
    byq = {q['quid']: q for q in test}
    samp, p3s, alloc, alloc3 = RC.draw_sample(test)
    S2000 = sorted(x for v in samp.values() for x in v)
    S600 = sorted(x for v in p3s.values() for x in v)
    assert len(S2000) == 2000 and len(set(S2000)) == 2000
    rule_sha = json.load(open(a.rule)).get('sha256') if a.rule else None
    GEN_MODEL = llm_client.model_id('gen')

    def gen_requests(items):
        return [{"prompt": RC.GEN_PROMPT.format(question=byq[x]['question']) +
                 (RC.GEN_RETRY_SUFFIX.format(previous=prev) if prev is not None else ""),
                 "model": GEN_MODEL, "max_tokens": RC.GEN_MAX_TOKENS} for x, prev in items]

    def mech(x, o):
        js = RC.extract_json(o.get('text'))
        para = js.get('paraphrase') if isinstance(js, dict) else None
        kept = js.get('kept_verbatim') if isinstance(js, dict) else None
        if para is None:
            return dict(paraphrase=None, kept=None, mech_ok=False, mech_reasons=['no_json'])
        ok, rs = RC.mechanical_check(byq[x]['question'], para, kept, L.parse_time)
        return dict(paraphrase=para.strip(), kept=kept, mech_ok=ok, mech_reasons=rs)

    records = {x: {'quid': x, 'qtype': byq[x]['qtype'], 'original': byq[x]['question'], 'attempts': []} for x in S600}

    # attempt 1
    items1 = [(x, None) for x in S600]
    out1 = []
    for s in range(0, len(items1), CHUNK):
        out1 += llm_client.complete(gen_requests(items1[s:s + CHUNK]), max_concurrency=a.max_concurrency)
    for x, o in zip(S600, out1):
        at = dict(attempt=1, model=o.get('model'), raw=o.get('text'), usage=o.get('usage'), stop_reason=o.get('stop_reason'))
        at.update(mech(x, o))
        records[x]['attempts'].append(at)
    m_ok = [x for x in S600 if records[x]['attempts'][0]['mech_ok']]

    def judge(xs, att_idx):
        reqs = [{"prompt": RC.JUDGE_PROMPT.format(original=byq[x]['question'], paraphrase=records[x]['attempts'][att_idx]['paraphrase']),
                 "max_tokens": RC.JUDGE_MAX_TOKENS} for x in xs]
        outs = []
        for s in range(0, len(reqs), CHUNK):
            outs += llm_client.complete(reqs[s:s + CHUNK], max_concurrency=a.max_concurrency, role='judge')
        for x, o in zip(xs, outs):
            js = RC.extract_json(o.get('text'))
            v = {k: (js.get(k) is True) for k in RC.JUDGE_KEYS} if isinstance(js, dict) else {k: False for k in RC.JUDGE_KEYS}
            records[x]['attempts'][att_idx].update(
                judge=dict(model=o.get('model'), raw=o.get('text'), usage=o.get('usage'), verdict=v,
                           note=(js or {}).get('note') if isinstance(js, dict) else None, parsed=isinstance(js, dict)),
                accepted=all(v.values()))

    judge(m_ok, 0)
    for x in S600:
        if not records[x]['attempts'][0]['mech_ok']:
            records[x]['attempts'][0]['accepted'] = False
    acc1 = [x for x in S600 if records[x]['attempts'][0]['accepted']]

    # attempt 2 for every rejected pool question
    rej1 = [x for x in S600 if not records[x]['attempts'][0]['accepted']]
    items2 = [(x, records[x]['attempts'][0]['paraphrase'] if records[x]['attempts'][0]['paraphrase'] else (records[x]['attempts'][0]['raw'] or ''))
              for x in rej1]
    out2 = llm_client.complete(gen_requests(items2), max_concurrency=a.max_concurrency)
    for (x, _), o in zip(items2, out2):
        at = dict(attempt=2, model=o.get('model'), raw=o.get('text'), usage=o.get('usage'), stop_reason=o.get('stop_reason'))
        at.update(mech(x, o))
        records[x]['attempts'].append(at)
    m2 = [x for x in rej1 if records[x]['attempts'][1]['mech_ok']]
    judge(m2, 1)
    for x in rej1:
        if not records[x]['attempts'][1]['mech_ok']:
            records[x]['attempts'][1]['accepted'] = False
    acc2 = [x for x in rej1 if records[x]['attempts'][1]['accepted']]

    accepted = {}
    for x in S600:
        for at in records[x]['attempts']:
            if at.get('accepted'):
                accepted[x] = at
                break

    def jacc(p, q):
        A = set(RC._norm_cmp(p).split()); B = set(RC._norm_cmp(q).split())
        return len(A & B) / max(1, len(A | B))

    by_qt_rate = {}
    for qt in sorted(alloc3):
        xs = [x for x in S600 if byq[x]['qtype'] == qt]
        by_qt_rate[qt] = dict(n=len(xs), accepted_attempt1=sum(records[x]['attempts'][0]['accepted'] for x in xs),
                              accepted_final=sum(x in accepted for x in xs),
                              rate_final=round(sum(x in accepted for x in xs) / len(xs), 4))

    variants = []
    for x in S2000:
        q = byq[x]['question']
        variants.append(dict(quid=x, variant='ORIG', vidx=0, squid=10 * x, question=q))
        variants.append(dict(quid=x, variant='P1', vidx=1, squid=10 * x + 1, question=RC.p1_prefix(q)))
        variants.append(dict(quid=x, variant='P2', vidx=2, squid=10 * x + 2, question=RC.p2_strip_qmark(q)))
    for x in S600:
        if x in accepted:
            variants.append(dict(quid=x, variant='P3', vidx=3, squid=10 * x + 3, question=accepted[x]['paraphrase']))
    variants.sort(key=lambda r: r['squid'])
    vtxt = json.dumps([[r['squid'], r['question']] for r in variants], ensure_ascii=False)

    tok = collections.Counter()
    for x in S600:
        for at in records[x]['attempts']:
            for kind, u in (('gen', at.get('usage') or {}), ('judge', (at.get('judge') or {}).get('usage') or {})):
                for k in ('input_tokens', 'output_tokens'):
                    tok[f'{kind}_{k}'] += u.get(k, 0)

    pset = dict(
        name='multitq_robustness_perturbed_set', rule_sha256=rule_sha,
        created_utc=datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ'),
        sample_quid_list_sha256=RC.list_sha(S2000), p3_pool_quid_list_sha256=RC.list_sha(S600),
        rob_common_sha256=fsha(os.path.join(HERE, 'rob_common.py')),
        generator_model=GEN_MODEL, generator_label='API LLM (GEN_MODEL_ID)',
        judge_model=records[m_ok[0]]['attempts'][0]['judge']['model'] if m_ok else None, judge_label='API LLM (JUDGE_MODEL_ID)',
        counts=dict(ORIG=2000, P1=2000, P2=2000,
                    P2_changed=sum(1 for x in S2000 if RC.p2_strip_qmark(byq[x]['question']) != byq[x]['question']),
                    P3_pool=600, P3_attempt1_mech_ok=len(m_ok), P3_attempt1_accepted=len(acc1), P3_attempt2_n=len(rej1),
                    P3_attempt2_mech_ok=len(m2), P3_attempt2_accepted=len(acc2), P3_accepted=len(accepted),
                    P3_rejected_final=600 - len(accepted), target_met=len(accepted) >= 450),
        acceptance_by_qtype=by_qt_rate,
        judge_rejection_reasons_attempt1=dict(collections.Counter(k for x in m_ok for k, v in records[x]['attempts'][0]['judge']['verdict'].items() if not v)),
        mechanical_rejections_attempt1=dict(collections.Counter(r.split(':')[0] for x in S600 for r in records[x]['attempts'][0]['mech_reasons'])),
        paraphrase_token_jaccard_vs_original=dict(
            mean=float(np.mean([jacc(byq[x]['question'], accepted[x]['paraphrase']) for x in accepted])) if accepted else None,
            median=float(np.median([jacc(byq[x]['question'], accepted[x]['paraphrase']) for x in accepted])) if accepted else None),
        api=dict(tokens=dict(tok)),
        variants=variants, variants_sha256=RC.sha256_text(vtxt),
        variants_sha256_recipe='sha256 of json.dumps([[squid, question] ...] sorted by squid, ensure_ascii=False)',
        p3_records=[records[x] for x in S600])
    raw = json.dumps(pset, sort_keys=True, ensure_ascii=False, default=str)
    pset['sha256'] = RC.sha256_text(raw)
    json.dump(pset, open(a.out, 'w'), ensure_ascii=False, indent=1, default=str)
    print(json.dumps(pset['counts']))


if __name__ == '__main__':
    main()
