#!/usr/bin/env python3
"""gk_finish_from_shards.py -- CPU-only completion of a split whose generations are cached as session shards
(e.g. a session that stopped after generating, before writing the ranked lists). Verifies that every shard was
generated by the frozen adapter (sha256 in the freeze file), rebuilds raw + ranked prediction files exactly as
gk_run_arm.py would, and adds their sha256 to the freeze. No model, no GPU, no scoring."""
import argparse, glob, json, os, sys, time
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gk_common as GC
import gk_infer as GI
import gk_select as GS


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--arm", required=True); ap.add_argument("--list", required=True); ap.add_argument("--split", required=True)
    ap.add_argument("--aname", required=True); ap.add_argument("--out", required=True); ap.add_argument("--bundles", required=True)
    ap.add_argument("--s_list", default=None); ap.add_argument("--kg", required=True); ap.add_argument("--tag", default="")
    a = ap.parse_args()
    fz = os.path.join(a.out, f"freeze_{a.arm}_{a.list}.json"); F = json.load(open(fz))
    ad_sha = F["adapter_sha256"]["adapter_model.safetensors"]
    sh = sorted(glob.glob(os.path.join(a.out, "shards", f"{a.arm}_{a.split}_{a.aname}{a.tag}_[0-9][0-9][0-9].json")))
    quids, texts, n_out, secs = [], [], [], 0.0
    for p in sh:
        d = json.load(open(p))
        assert d["adapter_sha256"] == ad_sha, f"{p}: shard adapter differs from the frozen adapter"
        quids += d["quids"]; texts += d["text"]; n_out += d["n_out"]; secs += d["seconds"]
    bl = sorted([GC.normalize_bundle(r) for r in GC.read_jsonl(a.bundles)], key=lambda b: b["quid"])
    assert quids == [b["quid"] for b in bl], "shard quids do not match the split's bundles"
    kg = GC.load_kg(a.kg); enorm = GC.entity_norm_map(sorted({f[0] for f in kg} | {f[2] for f in kg}))

    class _O:
        def __init__(self, t, n):
            self.text, self.token_ids = t, [0] * n

    class _R:
        def __init__(self, t, n):
            self.outputs = [_O(t, n)]
    raw, preds, inv = GI.postprocess(quids, [_R(t, n) for t, n in zip(texts, n_out)], enorm)
    s_lists = GI.load_s_lists(a.s_list, set(quids)) if a.s_list else None
    st = dict(n=len(quids), seconds=round(secs, 2), prompts_per_s=len(quids) / max(secs, 1e-9), invalid_rate=inv, n_shards=len(sh),
              finished_from_shards_utc=time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()), s_list=a.s_list,
              s_list_sha256=GC.sha256_file(a.s_list) if a.s_list else None, s_list_coverage=(len(s_lists) / len(quids)) if s_lists is not None else None)
    ns = argparse.Namespace(out=a.out, split=a.split, tag=a.tag)
    GI.write_outputs(ns, a.arm, a.aname, raw, preds, bl, s_lists, [], st, split=a.split)
    pt = os.path.join(a.out, st["pred_file"])
    GS.cmd_freeze(argparse.Namespace(out=fz, pred=pt, raw=pt.replace("/pred_", "/raw_").replace(".jsonl", ".jsonl.gz"), arm=None, list=None,
                                     run=None, adapter=None, selection=None, inputs="", order=None))
    json.dump(st, open(os.path.join(a.out, f"finish_{a.arm}_{a.split}_{a.aname}.json"), "w"), indent=1)
    print(json.dumps(st))


if __name__ == "__main__":
    main()
